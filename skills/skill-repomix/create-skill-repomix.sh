write_file "$TARGET_DIR/scripts/detect-language-profile" 0755 <<'EOF'
#!/usr/bin/env bash
set -Eeuo pipefail

REPO="$PWD"
JSON=0
PRIMARY_ONLY=0
EXPLAIN=0

usage() {
  cat <<'USAGE'
Usage: detect-language-profile [--repo PATH] [--json] [--primary-only] [--explain]
USAGE
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --repo) REPO="$2"; shift 2 ;;
    --json) JSON=1; shift ;;
    --primary-only) PRIMARY_ONLY=1; shift ;;
    --explain) EXPLAIN=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) printf 'Unknown option: %s\n' "$1" >&2; exit 2 ;;
  esac
done

REPO="$(cd "$REPO" && pwd)"
profiles=()
evidence=()

add_profile() {
  local p="$1" e="$2"
  profiles+=("$p")
  evidence+=("$e")
}

[[ -f "$REPO/pyproject.toml" || -f "$REPO/setup.py" || -f "$REPO/requirements.txt" ]] && add_profile python "python manifest"
[[ -f "$REPO/package.json" ]] && add_profile javascript-typescript "package.json"
[[ -f "$REPO/go.mod" || -f "$REPO/go.work" ]] && add_profile go "go manifest"
[[ -f "$REPO/Cargo.toml" ]] && add_profile rust "Cargo.toml"
[[ -f "$REPO/pom.xml" || -f "$REPO/build.gradle" || -f "$REPO/build.gradle.kts" ]] && add_profile java-kotlin "JVM build file"
compgen -G "$REPO/*.sln" >/dev/null && add_profile dotnet ".sln"
[[ -f "$REPO/Gemfile" ]] && add_profile ruby "Gemfile"
[[ -f "$REPO/composer.json" ]] && add_profile php "composer.json"
[[ -f "$REPO/ansible.cfg" || -d "$REPO/roles" || -d "$REPO/playbooks" ]] && add_profile ansible "Ansible structure"
find "$REPO" -maxdepth 2 -name '*.tf' -print -quit 2>/dev/null | grep -q . && add_profile terraform "*.tf"
[[ -f "$REPO/dbt_project.yml" || -d "$REPO/sql" || -d "$REPO/models" ]] && add_profile data-sql "data/SQL structure"
[[ -d "$REPO/docs" ]] && add_profile documentation "docs/"
find "$REPO" -maxdepth 2 \( -name '*.sh' -o -name 'Dockerfile' -o -name 'Makefile' \) -print -quit 2>/dev/null | grep -q . && add_profile bash "shell, Docker, or Makefile"

count="${#profiles[@]}"
if [[ "$count" -eq 0 ]]; then
  primary="base"
  secondary=""
  repo_type="unknown"
  recommended="base"
  confidence="low"
elif [[ "$count" -eq 1 ]]; then
  primary="${profiles[0]}"
  secondary=""
  repo_type="single"
  recommended="$primary"
  confidence="high"
else
  primary="${profiles[0]}"
  secondary="$(IFS=,; echo "${profiles[*]:1}")"
  repo_type="mixed"
  recommended="mixed-monorepo"
  confidence="high"
fi

if [[ "$PRIMARY_ONLY" -eq 1 ]]; then
  printf '%s\n' "$primary"
  exit 0
fi

if [[ "$JSON" -eq 1 ]]; then
  esc() { printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g'; }
  printf '{\n'
  printf '  "primary": "%s",\n' "$(esc "$primary")"
  printf '  "secondary": ['
  if [[ -n "$secondary" ]]; then
    IFS=',' read -r -a sec <<<"$secondary"
    for i in "${!sec[@]}"; do
      [[ "$i" -gt 0 ]] && printf ', '
      printf '"%s"' "$(esc "${sec[$i]}")"
    done
  fi
  printf '],\n'
  printf '  "repositoryType": "%s",\n' "$repo_type"
  printf '  "recommendedProfile": "%s",\n' "$recommended"
  printf '  "confidence": "%s",\n' "$confidence"
  printf '  "evidence": ['
  for i in "${!evidence[@]}"; do
    [[ "$i" -gt 0 ]] && printf ', '
    printf '"%s"' "$(esc "${evidence[$i]}")"
  done
  printf ']\n}\n'
else
  printf 'primary=%s\n' "$primary"
  printf 'secondary=%s\n' "$secondary"
  printf 'repository_type=%s\n' "$repo_type"
  printf 'recommended_profile=%s\n' "$recommended"
  printf 'confidence=%s\n' "$confidence"
  if [[ "$EXPLAIN" -eq 1 ]]; then
    printf 'evidence=%s\n' "$(IFS=';'; echo "${evidence[*]}")"
  fi
fi
EOF

# Wrapper generator
make_wrapper() {
  local name="$1" mode="$2" output="$3" compress_default="$4"
  write_file "$TARGET_DIR/scripts/$name" 0755 <<EOF
#!/usr/bin/env bash
set -Eeuo pipefail
SCRIPT_DIR="\$(cd "\$(dirname "\${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=_repomix-common.sh
source "\$SCRIPT_DIR/_repomix-common.sh"

REPO="\$PWD"
PROFILE="auto"
OUTPUT="$output"
INCLUDE=""
IGNORE=""
TOKEN_BUDGET=""
COMPRESS=$compress_default
WITH_LOGS=0
LOG_COUNT=10
REMOTE=""
REVISION=""
ALLOW_DEFAULT=0
FORCE=0
STYLE="xml"

usage() {
  cat <<'USAGE'
Usage: $name [options]
  --repo PATH
  --profile PROFILE
  --include PATTERNS
  --ignore PATTERNS
  --output PATH
  --token-budget NUMBER
  --compress
  --no-compress
  --with-logs
  --log-count NUMBER
  --revision VALUE
  --allow-default-branch
  --style xml|markdown|json|plain
  --force
USAGE
}

# shellcheck disable=SC2050,SC2194
if [[ "$mode" == "reference" ]]; then
  [[ \$# -gt 0 ]] || { usage; exit 2; }
  REMOTE="\$1"
  shift
fi

while [[ \$# -gt 0 ]]; do
  case "\$1" in
    --repo) REPO="\$2"; shift 2 ;;
    --profile) PROFILE="\$2"; shift 2 ;;
    --include) INCLUDE="\$2"; shift 2 ;;
    --ignore) IGNORE="\$2"; shift 2 ;;
    --output) OUTPUT="\$2"; shift 2 ;;
    --token-budget) TOKEN_BUDGET="\$2"; shift 2 ;;
    --compress) COMPRESS=1; shift ;;
    --no-compress) COMPRESS=0; shift ;;
    --with-logs) WITH_LOGS=1; shift ;;
    --log-count) LOG_COUNT="\$2"; shift 2 ;;
    --revision) REVISION="\$2"; shift 2 ;;
    --allow-default-branch) ALLOW_DEFAULT=1; shift ;;
    --style) STYLE="\$2"; shift 2 ;;
    --force) FORCE=1; shift ;;
    --no-security-check) die "--no-security-check is prohibited" ;;
    -h|--help) usage; exit 0 ;;
    *) die "Unknown option: \$1" ;;
  esac
done

REPO="\$(find_repo_root "\$REPO")"
assert_safe_repo "\$REPO"

if [[ "\$PROFILE" == "auto" ]]; then
  PROFILE="\$("\$SCRIPT_DIR/detect-language-profile" --repo "\$REPO" --primary-only)"
fi

# shellcheck disable=SC2050,SC2194
if [[ "$mode" == "reference" ]]; then
  if [[ -z "\$REVISION" && "\$ALLOW_DEFAULT" -ne 1 ]]; then
    die "A pinned --revision is required"
  fi
  safe_remote="\$(printf '%s' "\$REMOTE" | sed 's#https\?://##; s#[^A-Za-z0-9._-]#-#g')"
  safe_revision="\$(printf '%s' "\${REVISION:-default}" | sed 's#[^A-Za-z0-9._-]#-#g')"
  if [[ "\$OUTPUT" == "$output" ]]; then
    OUTPUT=".ai-context/references/\${safe_remote}-\${safe_revision}.xml"
  fi
fi

if [[ "\$OUTPUT" != /* ]]; then
  OUTPUT="\$REPO/\$OUTPUT"
fi
assert_safe_output "\$REPO" "\$OUTPUT"
mkdir -p "\$(dirname "\$OUTPUT")"
[[ ! -e "\$OUTPUT" || "\$FORCE" -eq 1 ]] || die "Output exists; use --force: \$OUTPUT"

read -r -a RBASE <<<"\$(repomix_cmd)"
cmd=("\${RBASE[@]}" --style "\$STYLE" --output "\$OUTPUT")

[[ -n "\$INCLUDE" ]] && cmd+=(--include "\$INCLUDE")
[[ -n "\$IGNORE" ]] && cmd+=(--ignore "\$IGNORE")
[[ -n "\$TOKEN_BUDGET" ]] && cmd+=(--token-budget "\$TOKEN_BUDGET")
[[ "\$COMPRESS" -eq 1 ]] && cmd+=(--compress)

# shellcheck disable=SC2050,SC2194
case "$mode" in
  review)
    cmd+=(--include-diffs)
    if [[ "\$WITH_LOGS" -eq 1 ]]; then
      cmd+=(--include-logs --include-logs-count "\$LOG_COUNT")
    fi
    ;;
  reference)
    cmd+=(--remote "\$REMOTE")
    [[ -n "\$REVISION" ]] && cmd+=(--remote-branch "\$REVISION")
    ;;
esac

printf 'Profile: %s\n' "\$PROFILE"
printf 'Output: %s\n' "\$OUTPUT"
printf 'Command:'
printf ' %q' "\${cmd[@]}"
printf '\n'
(cd "\$REPO" && "\${cmd[@]}")
EOF
}

