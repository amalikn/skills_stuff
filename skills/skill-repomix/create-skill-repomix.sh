copy_one() {
  local src="$1" dst="$2"
  if [[ -e "$dst" && "$FORCE" -ne 1 ]]; then
    printf 'SKIP existing: %s\n' "$dst"
    return
  fi
  if [[ "$DRY_RUN" -eq 1 ]]; then
    printf 'WOULD COPY: %s -> %s\n' "$src" "$dst"
  else
    mkdir -p "$(dirname "$dst")"
    cp "$src" "$dst"
  fi
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --project) PROJECT="$2"; shift 2 ;;
    --profile) PROFILE="$2"; shift 2 ;;
    --auto-profile) AUTO=1; shift ;;
    --with-wrappers) WITH_WRAPPERS=1; shift ;;
    --with-policy) WITH_POLICY=1; shift ;;
    --with-config) WITH_CONFIG=1; shift ;;
    --with-ignore) WITH_IGNORE=1; shift ;;
    --with-instruction) WITH_INSTRUCTION=1; shift ;;
    --force) FORCE=1; shift ;;
    --dry-run) DRY_RUN=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) printf 'Unknown option: %s\n' "$1" >&2; exit 2 ;;
  esac
done

[[ -n "$PROJECT" ]] || { usage; exit 2; }
PROJECT="$(cd "$PROJECT" && pwd)"

if [[ "$AUTO" -eq 1 ]]; then
  PROFILE="$("$SCRIPT_DIR/detect-language-profile" --repo "$PROJECT" --primary-only)"
