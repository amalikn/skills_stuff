#!/usr/bin/env bash
set -Eeuo pipefail

SCRIPT_NAME="$(basename "$0")"
TARGET_DIR="./skill-repomix"
FORCE=0
DRY_RUN=0

usage() {
  cat <<'EOF'
Usage:
  create-skill-repomix.sh [options]

Options:
  --target-dir PATH   Output directory. Default: ./skill-repomix
  --force             Overwrite an existing generated skill directory
  --dry-run           Show planned actions without writing files
  -h, --help          Show help
EOF
}

log() { printf '[%s] %s\n' "$SCRIPT_NAME" "$*"; }
die() { printf '[%s] ERROR: %s\n' "$SCRIPT_NAME" "$*" >&2; exit 1; }

while [[ $# -gt 0 ]]; do
  case "$1" in
    --target-dir)
      [[ $# -ge 2 ]] || die "--target-dir requires a path"
      TARGET_DIR="$2"
      shift 2
      ;;
    --force)
      FORCE=1
      shift
      ;;
    --dry-run)
      DRY_RUN=1
      shift
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      die "Unknown option: $1"
      ;;
  esac
done

[[ -n "$TARGET_DIR" ]] || die "Target directory cannot be empty"
[[ "$TARGET_DIR" != "/" ]] || die "Refusing to write to /"
[[ "$TARGET_DIR" != "$HOME" ]] || die "Refusing to overwrite home directory"

MARKER=".skill-repomix-generated"

if [[ -e "$TARGET_DIR" ]]; then
  if [[ ! -f "$TARGET_DIR/$MARKER" && "$FORCE" -ne 1 ]]; then
    die "Target exists and is not marked as generated. Use --force to overwrite: $TARGET_DIR"
  fi
fi

run() {
  if [[ "$DRY_RUN" -eq 1 ]]; then
    printf 'DRY-RUN:'
    printf ' %q' "$@"
    printf '\n'
  else
    "$@"
  fi
}

write_file() {
  local path="$1"
  local mode="${2:-0644}"
  local tmp
  tmp="$(mktemp)"
  cat > "$tmp"
  if [[ "$DRY_RUN" -eq 1 ]]; then
    log "Would write $path"
    rm -f "$tmp"
    return
  fi
  mkdir -p "$(dirname "$path")"
  mv "$tmp" "$path"
  chmod "$mode" "$path"
}

if [[ "$DRY_RUN" -eq 1 ]]; then
  log "Would create skill at $TARGET_DIR"
else
  if [[ -e "$TARGET_DIR" && "$FORCE" -eq 1 ]]; then
    rm -rf "$TARGET_DIR"
  fi
  mkdir -p "$TARGET_DIR"
fi

write_file "$TARGET_DIR/$MARKER" <<'EOF'
Generated by create-skill-repomix.sh
EOF

