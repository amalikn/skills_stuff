"""Offline tests for the generated banner (drawio.mxfile.banner) and the map check that guards it: "--" is illegal in an XML comment.

Run: `just test` (unittest, the pack's venv). The scripts folder is put on sys.path, as a consuming project does.
"""

from __future__ import annotations

import importlib
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
mxfile = importlib.import_module("drawio.mxfile")


class Banner(unittest.TestCase):
    """The banner is an XML comment, so no part of it may hold "--" (draw.io then refuses the file: "Export failed")."""

    def test_banner_refuses_double_dash(self) -> None:
        """A command with "--" would end the XML comment early, so banner() raises."""
        with self.assertRaises(ValueError):
            mxfile.banner("g.py", "m.yaml", "render_flowmap.py --write", "just check")

    def test_banner_accepts_recipe(self) -> None:
        """A recipe name is a well-formed comment."""
        self.assertTrue(mxfile.banner("g.py", "m.yaml", "just flows", "just check").startswith("<!-- GENERATED by g.py"))


if __name__ == "__main__":
    unittest.main()
