#!/usr/bin/env python3
"""Export a Pad workspace's items to one Markdown file, so the operator's Pad work has a readable, versioned copy in the project's repo.

Operator, 2026-11-10: Pad keeps everything in pad.db (outside Git); the operator chose "backup + Markdown export". Run from a folder whose .pad.toml
names the workspace (Pad resolves it from the current folder). Reads `pad item list --all --format json` (read-only), groups items by collection,
and writes a table per collection: ref, title, status, priority, updated, and the first line of the content. The file is rewritten only when an item
changed (the generated stamp alone is not a change), so a scheduled or pre-commit run leaves the tree clean when nothing moved.

Usage:
    python3 pad_export.py --out docs/trackers/pad-focus.md            # plan: item count, whether the file would change
    python3 pad_export.py --out docs/trackers/pad-focus.md --apply    # write it
Options: --pad PATH (the pad binary, default `pad`), --timeout SECONDS (60), --skip-collections conventions,playbooks (default; Pad's own scaffolding).
Exit: 0 done or plan clean, 1 pad failed or returned no JSON, 2 bad arguments. Budget: about 1 s for a personal workspace; the run prints its time.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import re
import subprocess
import sys
import time
from pathlib import Path

STAMP = re.compile(r"^Generated \d{4}-\d{2}-\d{2} \d{2}:\d{2} ", re.M)


def read_items(pad: str, timeout: int) -> list[dict]:
    """Every item of the current folder's workspace, done and archived included.

    Args:
        pad: the pad binary.
        timeout: seconds before the call is abandoned.

    Returns:
        The item dicts as `pad item list --format json` gives them.

    Raises:
        RuntimeError: pad failed, timed out or printed something that is not a JSON list.
    """
    cmd = [pad, "item", "list", "--all", "--format", "json"]
    try:
        p = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
    except (subprocess.TimeoutExpired, FileNotFoundError) as exc:
        raise RuntimeError(f"{' '.join(cmd)}: {exc}") from exc
    if p.returncode != 0:
        raise RuntimeError(f"{' '.join(cmd)} exited {p.returncode}: {p.stderr.strip()[-300:]}")
    try:
        items = json.loads(p.stdout)
    except json.JSONDecodeError as exc:
        raise RuntimeError(f"pad did not print JSON: {p.stdout[:200]!r}") from exc
    if not isinstance(items, list):
        raise RuntimeError("pad printed JSON that is not a list")
    return items


def cell(text: object) -> str:
    """A value made safe for one Markdown table cell (no pipes, no newlines, at most 120 characters).

    Args:
        text: any value.

    Returns:
        The cleaned text, `-` when empty.
    """
    s = " ".join(str(text or "").split()).replace("|", "/")
    return (s[:117] + "...") if len(s) > 120 else (s or "-")


def render(items: list[dict], workspace: str, stamp: str, skip: set[str]) -> str:
    """The Markdown page: front matter, a summary line, then one table per collection (newest change first).

    Args:
        items: item dicts from read_items().
        workspace: the workspace name, for the title.
        stamp: the generation time, YYYY-MM-DD hh:mm.
        skip: collection slugs left out.

    Returns:
        The page text.
    """
    kept = [i for i in items if i.get("collection_slug") not in skip]
    groups: dict[str, list[dict]] = {}
    for it in kept:
        groups.setdefault(it.get("collection_slug") or "other", []).append(it)
    lines = ["---", f"Title: Pad focus ({workspace})", "Category: living-tracker", "Status: generated",
             "Authority: the operator's Pad workspace (personal layer); the project's trackers stay the source of truth",
             f"Scope: every Pad item of workspace {workspace} outside Pad's own conventions and playbooks",
             "Summary: A readable, versioned copy of the operator's Pad items; generated by pad_export.py, never edited by hand.", "---", "",
             f"# Pad focus ({workspace})", "",
             f"Generated {stamp} from Pad by pad_export.py; do not edit (change the item in Pad). {len(kept)} item(s) in {len(groups)} collection(s).", ""]
    for slug in sorted(groups):
        rows = sorted(groups[slug], key=lambda i: i.get("updated_at", ""), reverse=True)
        lines += [f"## {slug}", "", "| Ref | Title | Status | Priority | Updated | Note |", "| --- | --- | --- | --- | --- | --- |"]
        for it in rows:
            f = it.get("fields") or {}
            if isinstance(f, str):
                f = json.loads(f or "{}")
            note = (it.get("content_preview") or it.get("content") or "").splitlines()[0] if (it.get("content_preview") or it.get("content")) else ""
            lines.append(f"| {cell(it.get('ref'))} | {cell(it.get('title'))} | {cell(f.get('status'))} | {cell(f.get('priority'))} | "
                         f"{cell((it.get('updated_at') or '')[:10])} | {cell(note)} |")
        lines.append("")
    return "\n".join(lines)


def changed(old: str | None, new: str) -> bool:
    """Whether the page differs from the file other than in its generated stamp.

    Args:
        old: the file's current text, or None when it does not exist.
        new: the rendered text.

    Returns:
        True when the file should be written.
    """
    return old is None or STAMP.sub("Generated X ", old) != STAMP.sub("Generated X ", new)


def main(argv: list[str] | None = None) -> int:
    """Read the workspace's items and write the page when something changed.

    Args:
        argv: command-line arguments (None reads sys.argv).

    Returns:
        The exit code: 0 done or plan clean, 1 pad failed.
    """
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", required=True, help="the Markdown file to write, relative to the current folder")
    ap.add_argument("--apply", action="store_true", help="write the file; without it only the plan is printed")
    ap.add_argument("--pad", default="pad")
    ap.add_argument("--timeout", type=int, default=60)
    ap.add_argument("--skip-collections", default="conventions,playbooks")
    args = ap.parse_args(argv)
    started = time.monotonic()
    toml = Path(".pad.toml")
    workspace = next((ln.split("=", 1)[1].strip().strip('"') for ln in toml.read_text(encoding="utf-8").splitlines()
                      if ln.startswith("workspace")), "?") if toml.exists() else "?"
    try:
        items = read_items(args.pad, args.timeout)
    except RuntimeError as exc:
        print(f"pad_export: {exc}", file=sys.stderr)
        return 1
    out = Path(args.out)
    page = render(items, workspace, dt.datetime.now().strftime("%Y-%m-%d %H:%M"), set(filter(None, args.skip_collections.split(","))))
    write = changed(out.read_text(encoding="utf-8") if out.exists() else None, page)
    if args.apply and write:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(page, encoding="utf-8")
    verb = ("wrote" if write else "unchanged") if args.apply else ("PLAN: would write" if write else "PLAN: unchanged")
    print(f"pad_export: {verb} {out} ({len(items)} item(s) read); {time.monotonic() - started:.1f} s")
    return 0


if __name__ == "__main__":
    sys.exit(main())
