#!/usr/bin/env python3
"""The docs/history layout: one subfolder per kind of rotated record, and the folder index generated with a summary line per file.

Why (operator, 2026-11-11: "docs/history: can you create sub directories and make it a standard ... other entries should also have this sort of
summary like the session records have"): one flat folder held 152 files in smc-resiliency and 369 in unified-network-controller, and each index line
said only "1 entries from CHANGELOG.md". The standard:

    docs/history/
      readme.md                       # the index: hand-written intro, then a generated block, one section per kind
      rotation-audit-baseline.txt     # stays at the top (audit_rotations.py)
      changelog/       changelog-<stamp>.md        (rotate_records.py)
      scratchpad/      scratchpad-<stamp>.md       (rotate_records.py; *-outbox.md variants too)
      roadmap/         roadmap-<stamp>.md          (roadmap_trim.py)
      session-records/ session-record-<stamp>.md   (slurp closeouts)
      sync/            sync-archive-<stamp>.md     (apn project_sync.py)

Readers find archives in both layouts (a project not yet migrated keeps its flat files); writers use the subfolder unless the project still has flat
archives of that kind at the top, so an unmigrated project stays consistent until `history_migrate.py` moves it.

Usage (library; the CLI prints the index a project would get, read-only):
    python3 history_layout.py --project-root <project>            # print the generated index block
Exit: 0 printed, 2 bad arguments.
Budget: one read per archive file; under 1 s for 400 files.
"""

from __future__ import annotations

import argparse
import os
import pathlib
import re
import sys

HISTORY = "docs/history"
#: (file-name prefix, subfolder, section title, what one unit is called), in index order.
KINDS: tuple[tuple[str, str, str, str], ...] = (
  ("changelog", "changelog", "Change log", "entries"),
  ("scratchpad", "scratchpad", "Scratchpad", "entries"),
  ("roadmap", "roadmap", "Roadmap", "done items"),
  ("session-record", "session-records", "Session records", ""),
  ("sync-archive", "sync", "Sync archive", "ticked items"),
)
START = "<!-- history-index:start (generated by skill-ai-it history_layout.py; descriptions written by hand are kept) -->"
END = "<!-- history-index:end -->"
#: Descriptions the old writers generated; anything else on an index line was written by a person and is kept.
GENERATED_DESC = re.compile(r"^\d+ (entries|done items|ticked sync items|ticked items)\b")
ROW = re.compile(r"^- \[([^\]]+)\]\(([^)]+)\)\s*(.*)$")
SUMMARY_CHARS = 220


def kind_of(name: str) -> tuple[str, str, str, str] | None:
  """The kind a history file belongs to, from its name.

  Args:
    name: a file name such as `changelog-20261110_0032.md`.

  Returns:
    The KINDS row, or None for a file that is not a rotated record (readme.md, the audit baseline).
  """
  for row in KINDS:
    if name.startswith(row[0] + "-") and name.endswith(".md"):
      return row
  return None


def subdir_for(prefix: str) -> str:
  """The subfolder for a kind.

  Args:
    prefix: a KINDS prefix (`changelog`, `session-record`, ...).

  Returns:
    The subfolder name.

  Raises:
    KeyError: an unknown prefix.
  """
  for p, sub, _, _ in KINDS:
    if p == prefix:
      return sub
  raise KeyError(prefix)


def archive_dir(root: pathlib.Path, prefix: str) -> str:
  """Where a writer puts a new archive of this kind, project-relative.

  Args:
    root: the project root.
    prefix: the kind's prefix.

  Returns:
    `docs/history/<subfolder>`, or `docs/history` while the project still keeps flat archives of that kind at the top (not migrated) or for a
    record of no known kind.
  """
  top = root / HISTORY
  flat = top.is_dir() and any(top.glob(f"{prefix}-*.md"))
  try:
    return HISTORY if flat else f"{HISTORY}/{subdir_for(prefix)}"
  except KeyError:  # a record of no known kind keeps the top folder
    return HISTORY


def archives(root: pathlib.Path, prefix: str) -> list[pathlib.Path]:
  """Every archive of a kind, in either layout, oldest first by name.

  Args:
    root: the project root.
    prefix: the kind's prefix, or a record stem (`changelog`, `scratchpad`, `roadmap`).

  Returns:
    The paths.
  """
  top = root / HISTORY
  found = list(top.glob(f"{prefix}-*.md"))
  try:
    found += list((top / subdir_for(prefix)).glob(f"{prefix}-*.md"))
  except KeyError:
    pass
  return sorted(set(found), key=lambda p: p.name)


def relink(text: str, source_dir: str, archive_dir: str) -> str:
  """Recompute relative Markdown link targets for text moving from one project folder to another (an archive is verbatim except its links).

  Args:
    text: Markdown.
    source_dir: the folder the links were written for, project-relative ("" for the root).
    archive_dir: the folder the text now lives in, project-relative.

  Returns:
    The text with each relative `](target)` recomputed; URLs, absolute paths and anchor-only targets unchanged.
  """
  def fix(m: re.Match) -> str:
    """One `](target)` match, its target recomputed or left as it is.

    Args:
      m: the regex match.

    Returns:
      The replacement text.
    """
    target = m.group(1)
    if re.match(r"^([a-z][a-z0-9+.-]*:|/|#)", target, re.I):
      return m.group(0)
    path, sep, anchor = target.partition("#")
    return f"]({os.path.relpath(os.path.normpath(os.path.join(source_dir, path)), archive_dir)}{sep}{anchor})"

  return re.sub(r"\]\(([^)\s]+)\)", fix, text)


def all_history_md(root: pathlib.Path) -> list[pathlib.Path]:
  """Every Markdown file under docs/history, both layouts (for sync-id and stamp lookups).

  Args:
    root: the project root.

  Returns:
    The paths.
  """
  top = root / HISTORY
  return sorted(top.rglob("*.md")) if top.is_dir() else []


def _front(text: str) -> dict[str, str]:
  """Front-matter keys of a file (first block between `---` lines), lower-cased; folded `>-` values joined.

  Args:
    text: the file.

  Returns:
    key -> value.
  """
  if not text.startswith("---\n"):
    return {}
  end = text.find("\n---", 4)
  out, key = {}, None
  for line in text[4:end].split("\n"):
    m = re.match(r"^([A-Za-z][\w -]*):\s*(.*)$", line)
    if m:
      key = m.group(1).strip().lower()
      out[key] = "" if m.group(2).strip() in (">-", ">", "|") else m.group(2).strip()
    elif key and line.startswith(" "):
      out[key] = (out[key] + " " + line.strip()).strip()
  return out


def _plain(text: str) -> str:
  """Markdown reduced to plain words for a summary: links to their text, emphasis and code marks removed, stamps and KEEP tags dropped.

  Args:
    text: one line of Markdown.

  Returns:
    The plain text.
  """
  t = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", text)
  t = re.sub(r"<!--.*?-->", "", t)
  t = re.sub(r"^\s*- (\[[ xX]\] )?", "", t)
  t = re.sub(r"\*\*\d{8}_\d{4}\*\*:?", "", t)
  t = t.replace("`KEEP`", "").replace("**", "").replace("`", "")
  t = re.sub(r"^\s*\((operator|USER_STATED)[^)]*\)\s*:?", "", t)
  return re.sub(r"\s+", " ", t).strip(" :;-")


def _words(text: str, n: int) -> str:
  """The first n words of plain text.

  Args:
    text: plain text.
    n: word count.

  Returns:
    The words, with `...` when cut.
  """
  w = text.split()
  return " ".join(w[:n]) + (" ..." if len(w) > n else "")


def _join(parts: list[str]) -> str:
  """Distinct parts joined with `; `, cut at SUMMARY_CHARS on a word.

  Args:
    parts: summary pieces in order.

  Returns:
    The summary.
  """
  seen, out = set(), []
  for p in (x for x in parts if x):
    if p not in seen:
      seen.add(p)
      out.append(p)
  s = "; ".join(out)
  return s if len(s) <= SUMMARY_CHARS else s[:SUMMARY_CHARS].rsplit(" ", 1)[0] + " ..."


def summary(path: pathlib.Path) -> str:
  """One index line's description for a history file, from its content.

  Args:
    path: the file.

  Returns:
    `<count and dates>: <what it is about>`; for a session record its front-matter Summary (or Title).
  """
  text = path.read_text(encoding="utf-8", errors="replace")
  head = _front(text)
  kind = kind_of(path.name)
  prefix = kind[0] if kind else ""
  body = text.split("\n---", 1)[1] if text.startswith("---\n") and "\n---" in text[4:] else text
  if prefix == "session-record" or not kind:
    return head.get("summary") or head.get("title") or _plain(next((l for l in body.split("\n") if l.startswith("# ")), path.stem)[2:])
  if prefix == "changelog":
    titles = [m.group(1) for m in re.finditer(r"^## .*? — (.+)$", body, re.M)]
    parts, n = titles, len(titles)
  elif prefix == "scratchpad":
    rows = re.findall(r"^\| (\d{8}_\d{4}) \| ([^|]*) \| (.*) \|$", body, re.M)
    if rows:
      parts = [f"{s.strip()}: {_words(_plain(first), 9)}" for _, s, first in rows]
      n = len(rows)
    else:
      items = [l for l in body.split("\n") if re.match(r"^- \*\*\d{8}_\d{4}\*\*", l)]
      parts, n = [_words(_plain(l), 9) for l in items], len(items)
  elif prefix == "roadmap":
    items = [l for l in body.split("\n") if l.startswith("- [x]")]
    parts, n = [_words(_plain(l), 8) for l in items], len(items)
  else:  # sync-archive
    items = [l for l in body.split("\n") if re.match(r"^- \[[xX]\] ", l)]
    parts, n = [_words(_plain(l), 9) for l in items], len(items)
  covers = head.get("covers", "")
  dates = re.findall(r"\d{4}-\d{2}-\d{2}", covers)
  span = f", {dates[0]} to {dates[-1]}" if dates else ""
  unit = kind[3] if n != 1 else {"entries": "entry", "done items": "done item", "ticked items": "ticked item"}.get(kind[3], kind[3])
  count = f"{n} {unit}{span}" if kind[3] else ""
  return f"{count}: {_join(parts)}" if parts else count


def _existing(index_text: str) -> dict[str, str]:
  """Descriptions written by hand in an index, by file name.

  Args:
    index_text: the current readme.

  Returns:
    file name -> its hand-written description (generated ones left out, so they are rebuilt).
  """
  out = {}
  for line in index_text.split("\n"):
    m = ROW.match(line)
    if m and m.group(3) and not GENERATED_DESC.match(m.group(3)):
      out[pathlib.PurePosixPath(m.group(2)).name] = m.group(3)
  return out


def index_block(root: pathlib.Path, current: str = "") -> str:
  """The generated part of docs/history/readme.md: one section per kind, newest first, a summary per file.

  Args:
    root: the project root.
    current: the readme's current text, whose hand-written descriptions are kept.

  Returns:
    The block, START and END markers included.
  """
  top = root / HISTORY
  keep = _existing(current)
  out = [START, ""]
  for prefix, sub, title, _ in KINDS:
    files = archives(root, prefix)
    if not files:
      continue
    out += [f"## {title}", ""]
    for f in sorted(files, key=lambda p: p.name, reverse=True):
      rel = f.relative_to(top).as_posix()
      out.append(f"- [{f.name}]({rel}) {keep.get(f.name) or summary(f)}")
    out.append("")
  others = sorted(p for p in top.rglob("*.md") if p.name != "readme.md" and not kind_of(p.name)) if top.is_dir() else []
  if others:
    out += ["## Other", ""] + [f"- [{p.name}]({p.relative_to(top).as_posix()}) {keep.get(p.name) or summary(p)}" for p in others] + [""]
  out.append(END)
  return "\n".join(out)


def render_index(root: pathlib.Path) -> str:
  """The whole docs/history/readme.md: the hand-written part kept, the generated block rebuilt.

  Args:
    root: the project root.

  Returns:
    The new readme text. On a readme without markers, everything before its first file line is kept as the intro and every old file line is
    replaced by the block.
  """
  path = root / HISTORY / "readme.md"
  current = path.read_text(encoding="utf-8") if path.is_file() else ""
  block = index_block(root, current)
  if START in current and END in current:
    return current[:current.index(START)] + block + current[current.index(END) + len(END):]
  intro = [l for l in current.split("\n")] if current else ["# History", "", "Rotated records, one folder per kind. Do not read these by default:"
                                                                " search with `just history <term>`, print one entry with `just history-show <stamp>`.", ""]
  first_row = next((i for i, l in enumerate(intro) if ROW.match(l)), None)
  rest = [l for l in intro[first_row:] if not ROW.match(l) and not l.startswith("## ")] if first_row is not None else []
  head = intro[:first_row] if first_row is not None else intro
  while head and not head[-1].strip():
    head.pop()
  tail = [l for l in rest if l.strip()]
  return "\n".join(head + ["", block] + ([""] + tail if tail else [])) + "\n"


def write_index(root: pathlib.Path) -> pathlib.Path:
  """Rewrite docs/history/readme.md from the files on disk.

  Args:
    root: the project root.

  Returns:
    The readme's path.
  """
  path = root / HISTORY / "readme.md"
  path.parent.mkdir(parents=True, exist_ok=True)
  path.write_text(render_index(root), encoding="utf-8")
  return path


def main(argv: list[str] | None = None) -> int:
  """Print the index block a project would get (read-only).

  Args:
    argv: command-line arguments (None reads sys.argv).

  Returns:
    Exit code: 0 printed, 2 bad arguments.
  """
  ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
  ap.add_argument("--project-root", type=pathlib.Path, required=True)
  a = ap.parse_args(argv)
  if not (a.project_root / HISTORY).is_dir():
    print(f"no {HISTORY} under {a.project_root}", file=sys.stderr)
    return 2
  print(index_block(a.project_root.resolve(), (a.project_root / HISTORY / "readme.md").read_text(encoding="utf-8")
                    if (a.project_root / HISTORY / "readme.md").is_file() else ""))
  return 0


if __name__ == "__main__":
  sys.exit(main())
