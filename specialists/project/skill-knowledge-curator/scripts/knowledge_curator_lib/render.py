"""Deterministic rendering of the project's knowledge/ pages and index.json from the ledgers.

Imported, not run. One page per primary category (the promotion unit), plus open-issues.md, history.md, index.md and index.json.
No timestamps, sorted everything: the same ledgers give the same bytes (INV-011). A promoted page is never overwritten; a changed
rendering goes to .kc/proposals/ for review instead. Output is scanned for secret-like strings and refused if any match.
Safety: returns texts; ledger.write_text does any writing.
"""

import json
import os
import re
from dataclasses import dataclass, field

from . import ids, settings
from .errors import ValidationFailed
from .state import State

BODY_MARK = "<!-- kc:body -->"
_SECRET = re.compile(
  r"(AKIA[0-9A-Z]{16}|gh[pousr]_[A-Za-z0-9]{30,}|-----BEGIN [A-Z ]*PRIVATE KEY-----|xox[abpr]-[A-Za-z0-9-]{10,}|"
  r"(password|passwd|secret|token|api[_-]?key)\s*[:=]\s*\S{6,})",
  re.IGNORECASE,
)


@dataclass
class Rendered:
  """Rendering outcome.

  Attributes:
    files: project-relative path -> text to write.
    proposals: project-relative proposal path -> text (promoted pages whose rendering changed).
    pages: page summaries for index.json and reports.
  """

  files: dict = field(default_factory=dict)
  proposals: dict = field(default_factory=dict)
  pages: list = field(default_factory=list)


def body_digest(text: str) -> str:
  """Digest of a page's body: everything after the body marker (front matter and banner excluded).

  Args:
    text: page text.

  Returns:
    SHA-256 hex of the body, or of the whole text when the marker is missing.
  """
  return ids.sha256_text(text.split(BODY_MARK, 1)[1] if BODY_MARK in text else text)


def _link(st: State, ev: dict) -> str:
  """Markdown link from the knowledge folder to an evidence span.

  Args:
    st: current state.
    ev: evidence record.

  Returns:
    "[path L1-2](relative#L1)".
  """
  rel = os.path.relpath(ev["path"], st.cfg["knowledge_dir"]).replace(os.sep, "/")
  return f"[{ev['path']} L{ev['line_start']}-{ev['line_end']}]({rel}#L{ev['line_start']})"


def _claim_line(st: State, cid: str) -> str:
  """One bullet for a claim with its kind, scope, sources and IDs.

  Args:
    st: current state.
    cid: claim ID.

  Returns:
    Markdown bullet.
  """
  c = st.claims[cid]
  parts = [f"- {c['claim_text']}", f"`{c['kind']}`"]
  if c["scope"]:
    parts.append("scope " + ", ".join(f"`{k}={v}`" for k, v in sorted(c["scope"].items())))
  links = ", ".join(_link(st, e) for e in c["evidence"])
  if links:
    parts.append(f"sources: {links} ({c['independent_sources']} independent)")
  if c.get("decision_id"):
    parts.append(f"decision `{c['decision_id']}`")
  parts.append(f"`{cid}`")
  return " · ".join(parts)


def _front_matter(title: str, status: str, summary: str) -> list[str]:
  """Front matter for a generated page (no dates, so reruns are byte-identical).

  Args:
    title: page title.
    status: derived or promoted.
    summary: one line.

  Returns:
    Lines including the fences.
  """
  return [
    "---",
    f"Title: {title}",
    "Category: knowledge-page",
    f"Status: {status}",
    "Authority: generated by skill-knowledge-curator from .kc/ ledgers"
    + ("; promoted by operator decision" if status == "promoted" else "; sources stay authoritative"),
    "Scope: curated knowledge view",
    "Last reviewed: generated",
    f"Summary: {summary}",
    "---",
    "",
  ]


def _category_page(st: State, cat: str, promoted: dict | None) -> tuple[str, dict]:
  """Text and summary of one category page.

  Args:
    st: current state.
    cat: category.
    promoted: the page's promotion record when promoted.

  Returns:
    (page text, summary).
  """
  ids_in = sorted(cid for cid, c in st.claims.items() if c["primary_category"] == cat)
  current = [cid for cid in ids_in if st.effective(cid) == "CURRENT"]
  unsettled = [cid for cid in ids_in if st.effective(cid) == "REVIEW_REQUIRED"]
  blocking = sorted({cf["conflict_id"] for cid in ids_in for cf in st.open_conflicts(cid) if cf["severity"] in settings.BLOCKING_SEVERITIES})
  status = "promoted" if promoted else "derived"
  head = _front_matter(cat.capitalize(), status, f"{len(current)} current claim(s), {len(unsettled)} not settled")
  banner = (
    f"> **Promoted** by decision `{promoted['decision_id']}`: authoritative. Change it only through kc review and kc promote."
    if promoted
    else "> **Derived view.** Generated by `kc render`; do not edit. The cited sources stay authoritative until this page is promoted."
  )
  body = ["", f"# {cat.capitalize()}", ""]
  if blocking:
    body += [f"> **Not settled:** open P0/P1 conflict(s) {', '.join(f'`{b}`' for b in blocking)}; see [open-issues.md](open-issues.md).", ""]
  topics: dict[str, list[str]] = {}
  for cid in current:
    topics.setdefault(st.claims[cid]["topic_key"], []).append(cid)
  for topic in sorted(topics):
    body += [f"## {topic}", ""] + [_claim_line(st, cid) for cid in topics[topic]] + [""]
  if unsettled:
    body += ["## Not settled (REVIEW_REQUIRED)", ""] + [_claim_line(st, cid) for cid in unsettled] + [""]
  if not current and not unsettled:
    body += ["No claims yet.", ""]
  text = "\n".join(head + [banner, "", BODY_MARK] + body).rstrip() + "\n"
  page = {"path": f"{st.cfg['knowledge_dir']}/{cat}.md", "category": cat, "status": status, "current": len(current), "not_settled": len(unsettled)}
  page["open_p0_p1"] = blocking
  return text, page


def _history_page(st: State) -> str:
  """History page: superseded, historical and duplicate claims with their successors.

  Args:
    st: current state.

  Returns:
    Page text.
  """
  body = ["", "# History", "", "Claims that were true for their time or restated elsewhere. Kept, never deleted.", ""]
  for disp in ("SUPERSEDED", "HISTORICAL", "DUPLICATE", "REJECTED"):
    rows = sorted(cid for cid in st.claims if st.disposition(cid) == disp)
    if not rows:
      continue
    body += [f"## {disp.capitalize()}", ""]
    for cid in rows:
      ev = st.dispositions[cid]
      link = ev.get("successor") or ev.get("duplicate_of")
      body.append(_claim_line(st, cid) + (f" · now `{link}`" if link else "") + f" · by `{ev['by']}`")
    body.append("")
  head = _front_matter("History", "derived", "superseded, historical, duplicate and rejected claims")
  return "\n".join(head + ["> **Derived view.** Generated by `kc render`; do not edit.", "", BODY_MARK] + body).rstrip() + "\n"


def _open_issues_page(st: State) -> str:
  """Open issues page: open conflicts and claims awaiting review.

  Args:
    st: current state.

  Returns:
    Page text.
  """
  body = ["", "# Open issues", ""]
  open_cf = st.open_conflicts()
  if not open_cf:
    body += ["No open conflicts.", ""]
  for cf in open_cf:
    texts = " vs ".join(f"“{st.claims[c]['claim_text']}”" for c in cf["claims"])
    body.append(f"- `{cf['conflict_id']}` **{cf['severity']}** `{cf['topic_key']}`: {cf['question']} ({texts})")
  lone = sorted(cid for cid in st.claims if st.disposition(cid) == "REVIEW_REQUIRED" and not st.open_conflicts(cid))
  if lone:
    body += ["", "## Claims awaiting review", ""] + [_claim_line(st, cid) for cid in lone]
  head = _front_matter("Open issues", "derived", f"{len(open_cf)} open conflict(s)")
  return "\n".join(head + ["> **Derived view.** Answer items with `kc review` and `kc decide`.", "", BODY_MARK] + body).rstrip() + "\n"


def _index_page(st: State, pages: list[dict]) -> str:
  """Human entry page.

  Args:
    st: current state.
    pages: category page summaries.

  Returns:
    Page text.
  """
  body = [
    "",
    f"# Knowledge index: {st.cfg['project_id']}",
    "",
    "Start here. Derived pages summarise the cited sources, which stay authoritative; a promoted page is authoritative itself.",
    "Agents: `kc query <text>` returns a claim with its disposition, conflicts and source lines.",
    "",
    "| Page | Status | Current | Not settled | Open P0/P1 |",
    "| --- | --- | --- | --- | --- |",
  ]
  for p in pages:
    name = p["path"].rsplit("/", 1)[-1]
    body.append(f"| [{name}]({name}) | {p['status']} | {p['current']} | {p['not_settled']} | {', '.join(p['open_p0_p1']) or 'none'} |")
  body += ["", "Also: [open-issues.md](open-issues.md), [history.md](history.md), machine index [index.json](index.json).", ""]
  head = _front_matter(f"Knowledge index {st.cfg['project_id']}", "derived", "navigation for humans and agents")
  return "\n".join(head + ["> **Derived view.** Generated by `kc render`; do not edit.", "", BODY_MARK] + body).rstrip() + "\n"


def _index_json(st: State, pages: list[dict]) -> str:
  """Machine index: pages and every claim with its disposition, page and evidence.

  Args:
    st: current state.
    pages: category page summaries.

  Returns:
    JSON text.
  """
  claims = []
  for cid in sorted(st.claims):
    c = st.claims[cid]
    claims.append(
      {
        "claim_id": cid,
        "text": c["claim_text"],
        "category": c["primary_category"],
        "topic_key": c["topic_key"],
        "disposition": st.effective(cid),
        "conflicts": [cf["conflict_id"] for cf in st.open_conflicts(cid)],
        "page": f"{st.cfg['knowledge_dir']}/{c['primary_category']}.md",
        "evidence": [{"path": e["path"], "lines": [e["line_start"], e["line_end"]]} for e in c["evidence"]],
      }
    )
  return json.dumps({"project": st.cfg["project_id"], "pages": pages, "claims": claims}, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def scan_secrets(files: dict) -> list[str]:
  """Paths whose text looks like it holds a credential (the value itself is never printed).

  Args:
    files: path -> text.

  Returns:
    Sorted paths with a match.
  """
  return sorted(path for path, text in files.items() if _SECRET.search(text))


def render(st: State) -> Rendered:
  """Render every knowledge file.

  Args:
    st: current state.

  Returns:
    The rendering.

  Raises:
    ValidationFailed: output contains a secret-like string.
  """
  out, kdir = Rendered(), st.cfg["knowledge_dir"]
  cats = sorted({c["primary_category"] for c in st.claims.values()} | {p.rsplit("/", 1)[-1][:-3] for p in st.promotions})
  for cat in (c for c in cats if c in settings.CATEGORIES):
    path = f"{kdir}/{cat}.md"
    promo = st.promotions.get(path)
    promo = promo if promo and promo["status"] == "promoted" else None
    text, page = _category_page(st, cat, promo)
    out.pages.append(page)
    on_disk = st.root / path
    if promo and on_disk.exists() and on_disk.read_text(encoding="utf-8") != text:
      out.proposals[f"{settings.KC_DIR}/proposals/{path}"] = text
    else:
      out.files[path] = text
  out.files[f"{kdir}/history.md"] = _history_page(st)
  out.files[f"{kdir}/open-issues.md"] = _open_issues_page(st)
  out.files[f"{kdir}/index.md"] = _index_page(st, out.pages)
  out.files[f"{kdir}/index.json"] = _index_json(st, out.pages)
  leaked = scan_secrets({**out.files, **out.proposals})
  if leaked:
    raise ValidationFailed("secret-like text in rendered output, nothing written: " + ", ".join(leaked))
  return out
